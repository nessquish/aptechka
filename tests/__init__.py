"""Автоматические тесты проекта (запуск: python -m unittest)."""

from pharmacy.utils import security

# В работе приложения хэш пароля считается 310 000 раз, чтобы пароль было
# трудно подобрать. В тестах столько повторений не нужны, они только замедляют
# запуск, поэтому здесь используется малое число. Проверка пароля читает
# число повторений из самого хэша, поэтому на результат тестов это не влияет.
security._ITERATIONS = 1_000
